// --- response post-processing --------------------------------------------
export function extractTsx(raw) {
  const fenced = raw.match(/```(?:tsx|typescript|ts|jsx)?\s*([\s\S]*?)```/i)
  return (fenced?.[1] ?? raw).trim()
}

export function postprocess(kind, raw) {
  const r = { raw, jsonOk: false, schemaOk: false, data: null, code: '', tsxOk: false }
  if (kind === 'brief') {
    let s = raw.trim().match(/```(?:json)?\s*([\s\S]*?)```/i)?.[1]?.trim() ?? raw.trim()
    try {
      r.data = JSON.parse(s)
      r.jsonOk = true
    } catch {
      try {
        r.data = JSON.parse(s.replace(/,\s*}/g, '}').replace(/,\s*]/g, ']').replace(/'/g, '"'))
        r.jsonOk = true
      } catch {
        /* stays false */
      }
    }
    if (r.jsonOk && r.data && typeof r.data === 'object') {
      r.schemaOk = ['status', 'questions', 'summary', 'assumptions', 'requirements'].every((k) => k in r.data)
    }
  } else {
    r.code = extractTsx(raw)
    r.tsxOk =
      /export\s+default/.test(r.code) && /<board[\s>]/.test(r.code) && !/^\s*```/m.test(r.code.trim())
  }
  return r
}

export function messagesFor(c) {
  return c.kind === 'brief'
    ? [{ role: 'system', content: BRIEF_SYSTEM }, { role: 'user', content: c.user }]
    : [{ role: 'system', content: CODEGEN_SYSTEM }, { role: 'user', content: c.user }]
}

export function jsonSchemaFor(c) {
  return c.kind === 'brief' ? BRIEF_SCHEMA : undefined
}
